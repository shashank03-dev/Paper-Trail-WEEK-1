/**
 * Reads the real font files and writes advance-width tables, so text can be
 * measured identically in the browser, on the server and in scripts.
 * Run: pnpm fonts:metrics
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
// @ts-expect-error opentype.js ships no types for this entry
import opentype from "opentype.js";

const FONTS: Record<string, string> = {
  "display-400": "fraunces/files/fraunces-latin-400-normal.woff",
  "display-600": "fraunces/files/fraunces-latin-600-normal.woff",
  "display-700": "fraunces/files/fraunces-latin-700-normal.woff",
  "display-400i": "fraunces/files/fraunces-latin-400-italic.woff",
  "ui-400": "inter/files/inter-latin-400-normal.woff",
  "ui-500": "inter/files/inter-latin-500-normal.woff",
  "ui-600": "inter/files/inter-latin-600-normal.woff",
  "mono-400": "ibm-plex-mono/files/ibm-plex-mono-latin-400-normal.woff",
  "mono-500": "ibm-plex-mono/files/ibm-plex-mono-latin-500-normal.woff",
  "hand-400": "caveat/files/caveat-latin-400-normal.woff",
  "hand-700": "caveat/files/caveat-latin-700-normal.woff",
};

const EXTRA = "‘’“”–—…•·★①②③④⑤⑥→↑";
const chars: string[] = [];
for (let c = 32; c <= 255; c++) chars.push(String.fromCharCode(c));
for (const ch of EXTRA) chars.push(ch);

const out: Record<string, { fallback: number; widths: Record<string, number> }> = {};
for (const [key, rel] of Object.entries(FONTS)) {
  const buf = readFileSync(join("node_modules/@fontsource", rel));
  const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
  const upm = font.unitsPerEm as number;
  const widths: Record<string, number> = {};
  let sum = 0;
  let n = 0;
  for (const ch of chars) {
    const g = font.charToGlyph(ch);
    if (!g || g.index === 0) continue;
    const w = Math.round(((g.advanceWidth ?? 0) / upm) * 1000);
    widths[ch] = w;
    if (/[a-z]/.test(ch)) {
      sum += w;
      n++;
    }
  }
  out[key] = { fallback: Math.round(sum / Math.max(1, n)), widths };
}

const header = `// Generated by scripts/gen-font-metrics.ts — do not edit by hand.
// Advance widths in 1/1000 em, from the self-hosted font files.
`;
writeFileSync(
  "lib/zine/metrics.generated.ts",
  `${header}export const FONT_METRICS: Record<string, { fallback: number; widths: Record<string, number> }> = ${JSON.stringify(out)};\n`,
);
console.log(`wrote metrics for ${Object.keys(out).length} fonts`);
